#!/usr/bin/env python3
"""Fail when a commit or pull-request message claims a model identity (backlog task 98).

The repository speaks about AI products all day long — `claude.ai` skill builds, `CLAUDE.md` files,
`.claude/skills/`, `GEMINI_API_KEY`, a provider list full of `openai/gpt-4.1` and `meta/Llama-3.3`.
None of that is a model identity claim, so this checker does not look for vendor *names*; it looks
for **authorship attribution**: a message saying a model wrote, generated or co-authored the change,
or speaking as an AI itself. A name-based filter would drown in false positives and get switched off.

Scope matters. This repository's inherited history already carries 181 `Co-Authored-By: Claude …`
trailers over 235 commits (measured 2026-10-20 with `--all-history`), and cleaning that up means
rewriting published history, which needs the owner's explicit approval. So the default scope is the
work under review — a revision range in CI (`origin/<base>...HEAD`), otherwise `HEAD` alone — and
`--all-history` exists for audits, not for gating. A gate that is red on inherited history gets
switched off, and then it protects nothing.

Scanning nothing is never reported as a pass: an unresolvable or empty range falls back to `HEAD`,
and only an empty repository (or empty `--stdin` without `--allow-empty`) is a usage error.

Usage:
  python3 scripts/check_commit_identity.py --range origin/main...HEAD   # the pull request's commits
  python3 scripts/check_commit_identity.py                              # HEAD only
  python3 scripts/check_commit_identity.py --all-history --json         # audit of everything
  git log -20 --format=%B | python3 scripts/check_commit_identity.py --stdin "branch"
Exit codes: 0 clean · 1 identity claim found · 2 nothing could be scanned
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

# (label, pattern). Each one needs an attribution verb or a first-person AI claim next to the name,
# except the co-author trailer, the robot emoji and the "AI-generated" marker, which are attribution
# by themselves. Deliberately NOT matched: bare product names, file paths, env vars and model ids
# such as `openai/gpt-4.1` (a slash or a dot after the version keeps them out of the version rule).
PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("co-author trailer", re.compile(
        r"Co-Authored-By:\s*[^\n]*\b(?:Claude|Anthropic|ChatGPT|OpenAI|Gemini|Copilot|Cursor|Aider|Codex)\b"
        r"|Co-Authored-By:\s*[^\n]*(?:anthropic|openai)\.com", re.IGNORECASE)),
    ("generated-with", re.compile(
        r"\b(?:generated|written|authored|drafted|created|produced|reviewed|maintained)\s+"
        r"(?:with|by|using|via)\s+(?:an?\s+)?(?:AI|LLM|language model|chatbot|Claude|ChatGPT|GPT|Gemini|"
        r"Copilot|Cursor|Aider|Codex|Anthropic|OpenAI)\b", re.IGNORECASE)),
    ("model-as-author", re.compile(
        r"\b(?:Claude|ChatGPT|GPT|Gemini|Copilot|Cursor|Aider|Codex|Anthropic|OpenAI)\s+"
        r"(?:wrote|writes|generated|authored|created|produced|drafted|made|suggested)\b", re.IGNORECASE)),
    ("ai-generated marker", re.compile(r"\bAI[- ]generated\b|\bgenerated by (?:an?\s+)?AI\b", re.IGNORECASE)),
    ("speaking as an AI", re.compile(
        r"\b(?:I am|I'm|as an|being an|speaking as)\s+(?:an?\s+)?(?:AI|LLM|language model|chatbot)\b", re.IGNORECASE)),
    ("robot emoji", re.compile("\U0001f916|\U0001f9be")),
    ("signed-off-by a bot", re.compile(
        r"Signed-off-by:\s*[^\n]*\b(?:Claude|Anthropic|ChatGPT|OpenAI|Gemini|Copilot|Cursor|Aider)\b", re.IGNORECASE)),
)

def find_identity_claims(text: str) -> list[dict[str, str]]:
    """Every attribution claim in one message, with the line it was found on."""
    findings = []
    for number, line in enumerate(str(text).splitlines(), start=1):
        for label, pattern in PATTERNS:
            match = pattern.search(line)
            if match:
                findings.append({"pattern": label, "line": number, "match": match.group(0)[:120],
                                 "context": line.strip()[:160]})
    return findings


def git(*args: str) -> str:
    result = subprocess.run(("git", *args), capture_output=True, text=True, timeout=120)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or f"git {' '.join(args)} failed")
    return result.stdout


def collect_commits(revision_range: str | None, limit: int) -> tuple[list[dict[str, str]], str]:
    """Commit messages to scan, plus a note about how they were chosen."""
    separator = "\x1e"
    if revision_range:
        try:
            raw = git("log", f"--format=%H{separator}%B{separator}", revision_range)
        except RuntimeError as error:
            raw = ""
            note = f"range {revision_range!r} could not be resolved ({error}); "
        else:
            note = f"range {revision_range!r}; "
        messages = parse_log(raw, separator)
        if messages:
            return messages, note + f"{len(messages)} commit(s) scanned"
        scope = "every reachable commit" if not limit else f"the last {limit} commit(s) of this branch"
        note += f"it holds no commits, so {scope} were scanned instead"
        raw = git("log", *(["-n", str(limit)] if limit else []), f"--format=%H{separator}%B{separator}")
        return parse_log(raw, separator), note
    scope = "every reachable commit" if not limit else f"the last {limit} commit(s) of the current branch"
    raw = git("log", *(["-n", str(limit)] if limit else []), f"--format=%H{separator}%B{separator}")
    return parse_log(raw, separator), scope


def parse_log(raw: str, separator: str) -> list[dict[str, str]]:
    messages = []
    for chunk in raw.split(separator + "\n"):
        chunk = chunk.strip("\n")
        if not chunk:
            continue
        sha, _, body = chunk.partition(separator)
        if sha.strip():
            messages.append({"sha": sha.strip()[:12], "text": body})
    return messages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="check_commit_identity")
    parser.add_argument("--range", dest="revision_range", default=None,
                        help="git revision range to scan, e.g. origin/main...HEAD (the pull-request commits)")
    parser.add_argument("--limit", type=int, default=1,
                        help="how many recent commits to scan when no range is given (default: HEAD only)")
    parser.add_argument("--all-history", action="store_true",
                        help="audit every reachable commit; inherited history is known not to be clean")
    parser.add_argument("--stdin", metavar="LABEL", default=None, help="scan one message read from stdin")
    parser.add_argument("--messages-file", type=Path, default=None, help="scan messages from a file (one per \\x1e-separated block)")
    parser.add_argument("--allow-empty", action="store_true", help="empty input is a pass (for optional CI steps)")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    note = ""
    revision_range = args.revision_range
    limit = 0 if args.all_history else args.limit
    if args.all_history:
        revision_range = None
    if args.stdin is not None:
        text = sys.stdin.read()
        messages = [{"sha": args.stdin, "text": text}] if text.strip() else []
        note = f"stdin message labelled {args.stdin!r}"
    elif args.messages_file is not None:
        if not args.messages_file.is_file():
            print(f"no such file: {args.messages_file}", file=sys.stderr)
            return 2
        messages = parse_log(args.messages_file.read_text(encoding="utf-8"), "\x1e")
        note = f"messages from {args.messages_file}"
    else:
        try:
            messages, note = collect_commits(revision_range, limit)
        except (RuntimeError, subprocess.SubprocessError) as error:
            print(f"could not read the git history: {error}", file=sys.stderr)
            return 2

    if not messages:
        if args.allow_empty:
            print("nothing to scan; --allow-empty was given, so this is not a failure")
            return 0
        print("nothing to scan: refusing to report a pass without a message to read", file=sys.stderr)
        return 2

    findings = []
    for message in messages:
        for claim in find_identity_claims(message["text"]):
            findings.append({"commit": message["sha"], **claim})

    if args.json:
        print(json.dumps({"scanned": len(messages), "note": note, "findings": findings}, ensure_ascii=False, indent=2))
    else:
        print(f"commit/PR identity check — {note}")
        if findings:
            for item in findings:
                print(f"  {item['commit']} line {item['line']}: {item['pattern']} → {item['match']!r}")
                print(f"    context: {item['context']}")
            print(f"{len(findings)} identity claim(s) in {len(messages)} message(s): "
                  "describe the change, not the tool that helped make it.")
        else:
            print(f"clean: {len(messages)} message(s), no model-identity attribution")
    return 1 if findings else 0


if __name__ == "__main__":
    raise SystemExit(main())
