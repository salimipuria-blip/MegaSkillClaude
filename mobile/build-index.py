#!/usr/bin/env python3
"""Build and validate the compact, offline skills index for the iPhone console.

The canonical source is ``.claude/skills/mega-skills-router/references/triggers.json``.
Never edit ``mobile/skills-index.json`` or the generated cache key in ``mobile/sw.js``
by hand. The cache fingerprint covers the index, every precached asset, and the
service-worker implementation (with its generated cache line normalized).

    python3 mobile/build-index.py           # regenerate index + PWA cache version
    python3 mobile/build-index.py --check   # read-only drift check for both outputs
"""
from __future__ import annotations

import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOBILE = ROOT / "mobile"
SOURCE = ROOT / ".claude/skills/mega-skills-router/references/triggers.json"
OUTPUT = MOBILE / "skills-index.json"
SERVICE_WORKER = MOBILE / "sw.js"
CACHE_PREFIX = "mega-mobile-"
CACHE_TEMPLATE = 'const CACHE = "mega-mobile-v1"; // generated by build-index.py'
CACHE_LINE = re.compile(r'(?m)^const CACHE = "mega-mobile-[^"]+"; // generated by build-index\.py$')

# Keep in sync with ASSETS in sw.js. Paths are also included in the fingerprint,
# so changing the pre-cache contract invalidates the old PWA cache.
PRECACHE_ASSETS = (
    "index.html",
    "styles.css",
    "app.js",
    "search.mjs",
    "manifest.webmanifest",
    "skills-index.json",
    "icon.svg",
    "icon-192.png",
    "icon-512.png",
    "apple-touch-icon.png",
)


# The index is precached whole, so it is downloaded on every install-to-home-screen and parsed on
# every cold start. 2.2 MB raw (~0.4 MB gzipped) is the measured size today; the budget is the point
# at which it must be split by domain (or streamed) instead of growing silently on a phone.
SIZE_BUDGET_BYTES = 3 * 1024 * 1024


def build_index() -> bytes:
    payload = json.loads(SOURCE.read_text(encoding="utf-8"))
    skills = [
        {
            "n": skill["name"],
            "d": skill["domain"],
            "p": skill["source_path"],
            # A few triggers are enough for on-device search; the full
            # 30k-trigger index stays in the router for Claude Code.
            "t": skill.get("triggers", [])[:5],
        }
        for skill in payload["skills"]
        if not skill.get("incomplete")  # incomplete skills are manual-review only
    ]
    document = {
        "schema": "mega-skills-mobile/v1",
        "counts": {"routable_skills": len(skills)},
        "skills": skills,
    }
    return (json.dumps(document, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")


def cache_version(index_bytes: bytes) -> str:
    """Fingerprint all precached content and worker behavior deterministically."""
    digest = hashlib.sha256()
    for relative_path in PRECACHE_ASSETS:
        content = index_bytes if relative_path == "skills-index.json" else (MOBILE / relative_path).read_bytes()
        digest.update(relative_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(content)
        digest.update(b"\0")

    source = SERVICE_WORKER.read_text(encoding="utf-8")
    normalized, replacements = CACHE_LINE.subn(CACHE_TEMPLATE, source)
    if replacements != 1:
        raise ValueError(
            "mobile/sw.js must contain exactly one generated cache declaration: "
            f"{CACHE_TEMPLATE}"
        )
    digest.update(b"sw.js\0")
    digest.update(normalized.encode("utf-8"))
    return digest.hexdigest()[:16]


def build_service_worker(index_bytes: bytes) -> tuple[bytes, str]:
    source = SERVICE_WORKER.read_text(encoding="utf-8")
    normalized, replacements = CACHE_LINE.subn(CACHE_TEMPLATE, source)
    if replacements != 1:
        raise ValueError(
            "mobile/sw.js must contain exactly one generated cache declaration: "
            f"{CACHE_TEMPLATE}"
        )

    version = cache_version(index_bytes)
    cache_name = f"{CACHE_PREFIX}v1-{version}"
    generated_line = f'const CACHE = "{cache_name}"; // generated by build-index.py'
    output, replacements = CACHE_LINE.subn(generated_line, source)
    if replacements != 1:
        raise ValueError("failed to update the generated mobile service-worker cache key")
    return output.encode("utf-8"), cache_name


def check() -> int:
    index_bytes = build_index()
    service_worker_bytes, cache_name = build_service_worker(index_bytes)
    errors = []
    if not OUTPUT.exists() or OUTPUT.read_bytes() != index_bytes:
        errors.append("mobile/skills-index.json is stale")
    if not SERVICE_WORKER.exists() or SERVICE_WORKER.read_bytes() != service_worker_bytes:
        errors.append("mobile/sw.js cache fingerprint is stale")
    if len(index_bytes) > SIZE_BUDGET_BYTES:
        errors.append(
            f"index is {len(index_bytes)} bytes, over the {SIZE_BUDGET_BYTES}-byte budget: "
            "split it by domain or stream it instead of precaching one blob"
        )

    if errors:
        print("ERROR: " + "; ".join(errors) + "; run python3 mobile/build-index.py", file=sys.stderr)
        return 2

    count = json.loads(index_bytes)["counts"]["routable_skills"]
    gzipped = len(gzip.compress(index_bytes, 9))
    print(
        f"mobile PWA: OK ({count} routable skills; cache {cache_name}; "
        f"{len(index_bytes)} bytes raw / {gzipped} bytes gzipped, budget {SIZE_BUDGET_BYTES})"
    )
    return 0


def main() -> int:
    try:
        index_bytes = build_index()
        if "--check" in sys.argv:
            return check()
        service_worker_bytes, cache_name = build_service_worker(index_bytes)
        OUTPUT.write_bytes(index_bytes)
        SERVICE_WORKER.write_bytes(service_worker_bytes)
    except (OSError, KeyError, TypeError, ValueError, json.JSONDecodeError) as error:
        print(f"ERROR: could not build the mobile PWA index: {error}", file=sys.stderr)
        return 2

    count = json.loads(index_bytes)["counts"]["routable_skills"]
    gzipped = len(gzip.compress(index_bytes, 9))
    print(
        f"wrote {OUTPUT.relative_to(ROOT)} ({len(index_bytes)} bytes raw / {gzipped} gzipped; {count} skills)"
    )
    print(f"updated mobile/sw.js cache fingerprint: {cache_name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
