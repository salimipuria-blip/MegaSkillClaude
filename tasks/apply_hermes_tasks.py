#!/usr/bin/env python3
"""
Apply Hermes task set to repo.
"""
import argparse, json, os, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def run(cmd, shell=False):
    if shell:
        res = subprocess.run(cmd, shell=True, cwd=str(ROOT), text=True)
    else:
        res = subprocess.run(cmd, cwd=str(ROOT), text=True)
    if res.returncode != 0:
        raise RuntimeError(f"Command failed: {cmd}\n{res.stdout}\n{res.stderr}")
    return res


def ensure_clean():
    status = subprocess.run(["git", "status", "--porcelain"], cwd=str(ROOT), text=True, capture_output=True)
    if status.stdout.strip():
        raise RuntimeError("Working tree not clean. Commit or stash existing changes first.")


def ensure_branch(branch_name):
    try:
        run(["git", "checkout", branch_name])
    except Exception:
        run(["git", "checkout", "-b", branch_name])


def write_file(rel_path, content):
    p = ROOT / rel_path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf8")


def task_files(task):
    files = []
    for f in task.get("files", []):
        files.append(f)
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", default="tasks/hermes_tasks.json")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    manifest = ROOT / args.manifest
    if not manifest.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest}")

    data = json.loads(manifest.read_text(encoding="utf8"))
    tasks = data.get("tasks", [])

    for task in tasks:
        print(f"\n=== {task['id']}: {task['title']} ===")
        branch_name = task["branch"]
        commit_msg = task["commit"]
        pr_title = task["pr_title"]
        pr_body = task["pr_body"]
        files = task_files(task)

        if args.dry_run:
            print(f"[dry-run] would checkout {branch_name} and modify: {files}")
            continue

        ensure_clean()
        ensure_branch(branch_name)

        for file_path in files:
            ext = file_path.split(".")[-1].lower()
            if ext in {"sh"}:
                content = "#!/usr/bin/env bash\nset -euo pipefail\n# created by Hermes automation\n"
            elif ext in {"md"}:
                content = f"# {task['title']}\n\n{task['summary']}\n"
            elif ext in {"js", "mjs", "cjs", "ts"}:
                content = "// created by Hermes automation\n"
            elif ext in {"yaml", "yml"}:
                content = "# GitHub Actions workflow generated by Hermes automation\n"
            else:
                content = f"# created by Hermes automation for {task['title']}\n"

            if not (ROOT / file_path).exists():
                write_file(file_path, content)
                print(f"created {file_path}")

        run(["git", "add", "-A"])
        try:
            run(["git", "commit", "-m", commit_msg])
            print(f"committed: {commit_msg}")
        except Exception as exc:
            print(f"commit skipped: {exc}")

        run(["git", "push", "--set-upstream", "origin", branch_name])
        print(f"pushed {branch_name}")

        pr_cmd = [
            "gh", "pr", "create",
            "--title", pr_title,
            "--body", pr_body,
            "--base", "main",
            "--head", branch_name,
        ]
        try:
            run(pr_cmd)
            print(f"PR created: {pr_title}")
        except Exception as exc:
            print(f"PR creation failed: {exc}")

        time.sleep(1)

if __name__ == "__main__":
    main()
